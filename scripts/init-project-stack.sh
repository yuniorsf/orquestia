#!/usr/bin/env bash
# ==============================================================================
# Project Stack Initializer
# ==============================================================================
# Configures `.harness/harness.env` and `harness.config.json`. Orquestia is a
# permanent TypeScript/Node project (see harness.config.json's "stack" field),
# so the other-language profiles from the original multi-stack template
# (python-uv/go/rust/dotnet) were removed as unused; this now only supports
# re-generating the typescript-node profile or a fully manual "generic" one.
#
# Usage:
#   ./scripts/init-project-stack.sh <typescript|generic> [ProjectName] [TICKET_PREFIX]
# ==============================================================================

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILES_DIR="${REPO_ROOT}/.harness/profiles"
TARGET_ENV="${REPO_ROOT}/.harness/harness.env"
CONFIG_JSON="${REPO_ROOT}/harness.config.json"

STACK_ARG="${1:-}"
PROJECT_NAME_ARG="${2:-$(basename "${REPO_ROOT}")}"
TICKET_PREFIX_ARG="${3:-PROJ}"

if [[ -z "${STACK_ARG}" || "${STACK_ARG}" == "-h" || "${STACK_ARG}" == "--help" ]]; then
    cat <<EOF
Usage: $(basename "$0") <stack> [ProjectName] [TICKET_PREFIX]

Available stacks:
  typescript   -> .harness/profiles/typescript-node.env (Prettier + tsc + ESLint + Vitest/Jest)
  generic      -> Polyglot SOLID verifier defaults (customize .harness/harness.env manually)
EOF
    exit 0
fi

case "${STACK_ARG}" in
    ts|typescript|node|typescript-node) PROFILE_FILE="${PROFILES_DIR}/typescript-node.env"; STACK_ID="typescript-node" ;;
    generic)                            PROFILE_FILE="";                                    STACK_ID="generic" ;;
    *)
        printf "\033[1;31m[INIT:ERROR]\033[0m Unknown stack '%s'. Run with --help to list supported stacks.\n" "${STACK_ARG}" >&2
        exit 2
        ;;
esac

if [[ -n "${PROFILE_FILE}" ]]; then
    {
        printf "# Auto-generated by scripts/init-project-stack.sh for %s (%s)\n" "${PROJECT_NAME_ARG}" "${STACK_ID}"
        printf "PROJECT_NAME=\"%s\"\n" "${PROJECT_NAME_ARG}"
        printf "TICKET_PREFIX=\"%s\"\n\n" "${TICKET_PREFIX_ARG}"
        cat "${PROFILE_FILE}"
    } > "${TARGET_ENV}"
fi

python3 - "${CONFIG_JSON}" "${PROJECT_NAME_ARG}" "${STACK_ID}" "${TICKET_PREFIX_ARG}" <<'PY'
import json
import sys
from pathlib import Path

cfg_path = Path(sys.argv[1])
data = json.loads(cfg_path.read_text(encoding="utf-8"))
data.setdefault("project", {})
data["project"]["name"] = sys.argv[2]
data["project"]["stack"] = sys.argv[3]
data["project"]["ticketPrefix"] = sys.argv[4]
cfg_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
PY

printf "\033[1;32m[INIT:OK]\033[0m Configured project '%s' (stack: %s, ticket prefix: %s).\n" \
    "${PROJECT_NAME_ARG}" "${STACK_ID}" "${TICKET_PREFIX_ARG}"
printf "  - Active Oracle profile : %s\n" "${TARGET_ENV}"
printf "  - Polyglot SOLID config : %s\n" "${CONFIG_JSON}"
